/// Formats a byte size into a human-readable string (e.g. "14.2 GB", "350 MB").
pub fn format_bytes(bytes: u64) -> String {
    const KB: u64 = 1024;
    const MB: u64 = 1024 * 1024;
    const GB: u64 = 1024 * 1024 * 1024;
    const TB: u64 = 1024 * 1024 * 1024 * 1024;

    if bytes >= TB {
        format!("{:.2} TB", bytes as f64 / TB as f64)
    } else if bytes >= GB {
        format!("{:.2} GB", bytes as f64 / GB as f64)
    } else if bytes >= MB {
        format!("{:.2} MB", bytes as f64 / MB as f64)
    } else if bytes >= KB {
        format!("{:.2} KB", bytes as f64 / KB as f64)
    } else {
        format!("{} B", bytes)
    }
}

/// Parses a human-formatted size string (e.g. "10GB", "500MB", "15G", "1.5GB") into bytes.
pub fn parse_size_to_bytes(s: &str) -> Result<u64> {
    let s = s.trim();
    if s.is_empty() {
        anyhow::bail!("Size string cannot be empty");
    }

    let (num_part, multiplier) = if let Some(n) = s
        .strip_suffix("TB")
        .or_else(|| s.strip_suffix("tb"))
        .or_else(|| s.strip_suffix('T'))
        .or_else(|| s.strip_suffix('t'))
    {
        (n.trim(), 1024u64 * 1024 * 1024 * 1024)
    } else if let Some(n) = s
        .strip_suffix("GB")
        .or_else(|| s.strip_suffix("gb"))
        .or_else(|| s.strip_suffix('G'))
        .or_else(|| s.strip_suffix('g'))
    {
        (n.trim(), 1024u64 * 1024 * 1024)
    } else if let Some(n) = s
        .strip_suffix("MB")
        .or_else(|| s.strip_suffix("mb"))
        .or_else(|| s.strip_suffix('M'))
        .or_else(|| s.strip_suffix('m'))
    {
        (n.trim(), 1024u64 * 1024)
    } else if let Some(n) = s
        .strip_suffix("KB")
        .or_else(|| s.strip_suffix("kb"))
        .or_else(|| s.strip_suffix('K'))
        .or_else(|| s.strip_suffix('k'))
    {
        (n.trim(), 1024u64)
    } else if let Some(n) = s.strip_suffix('B').or_else(|| s.strip_suffix('b')) {
        (n.trim(), 1u64)
    } else {
        // Raw number without unit defaults to Gigabytes
        (s, 1024u64 * 1024 * 1024)
    };

    if let Ok(float_val) = num_part.parse::<f64>() {
        if float_val <= 0.0 {
            anyhow::bail!("Size must be greater than zero");
        }
        Ok((float_val * multiplier as f64) as u64)
    } else {
        let int_val: u64 = num_part
            .parse()
            .with_context(|| format!("Invalid numeric value in size: '{num_part}'"))?;
        if int_val == 0 {
            anyhow::bail!("Size must be greater than zero");
        }
        Ok(int_val.saturating_mul(multiplier))
    }
}

/// A candidate artifact directory proposed for reclamation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ReclaimCandidate {
    pub path: PathBuf,
    pub artifact_label: String,
    pub kind_slug: String,
    pub icon: String,
    pub size_bytes: u64,
    pub formatted_size: String,
    pub risk_level: RiskLevel,
    pub days_inactive: Option<u64>,
    pub git_branch: Option<String>,
    pub git_dirty: bool,
    pub recovery_command: Option<String>,
    pub score: u64,
    pub rationale: String,
}

/// The complete plan generated by the Cleanup Budget engine.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ReclaimPlan {
    pub target_bytes: u64,
    pub proposed_bytes: u64,
    pub formatted_target: String,
    pub formatted_proposed: String,
    pub met_target: bool,
    pub candidates: Vec<ReclaimCandidate>,
    pub pinned_skipped_count: usize,
    pub pinned_skipped_bytes: u64,
    pub total_scanned_bytes: u64,
    pub profile_applied: Option<String>,
}

/// Plans an optimal reclamation set to achieve `target_bytes` from discovered `entries`.
///
/// Principles:
/// 1. Safety first: Pinned projects and paths are strictly excluded.
/// 2. Profile constraints: If a profile is active, only matching entries are considered.
/// 3. Risk scoring: Zero-download local compilation outputs (Low risk) are prioritized.
/// 4. Staleness bonus: Old, untouched projects get higher score.
/// 5. Git safety: Repositories with uncommitted (dirty) changes are de-prioritized.
pub fn plan_reclaim(
    entries: &[Entry],
    target_bytes: u64,
    prefer_local_rebuild: bool,
    profile: Option<ProfileKind>,
) -> ReclaimPlan {
    let mut candidates: Vec<ReclaimCandidate> = Vec::new();
    let mut pinned_skipped_count = 0;
    let mut pinned_skipped_bytes = 0;
    let mut total_scanned_bytes = 0;

    for entry in entries {
        total_scanned_bytes += entry.size_bytes;

        // Skip pinned projects
        if is_path_pinned(&entry.path) {
            pinned_skipped_count += 1;
            pinned_skipped_bytes += entry.size_bytes;
            continue;
        }

        // Apply profile filter if requested
        if profile.is_some_and(|prof| !prof.includes_kind(entry.kind)) {
            continue;
        }

        let explanation = explain_entry(entry);

        // Scoring algorithm:
        // Base risk weight
        let (base_risk, risk_rationale) = match explanation.risk_level {
            RiskLevel::Low => {
                let score = if prefer_local_rebuild { 25_000 } else { 15_000 };
                (score, "safe local rebuild (zero network download)")
            }
            RiskLevel::Moderate => {
                let score = if prefer_local_rebuild { 10_000 } else { 15_000 };
                (
                    score,
                    "standard dependency cache (re-downloads from registry)",
                )
            }
            RiskLevel::Caution => (
                1_000,
                "model/environment cache (may require manual reconfiguration)",
            ),
        };

        // Staleness weight: up to 5,000 points
        let days = explanation
            .source_staleness
            .as_ref()
            .map(|s| s.stale_days)
            .unwrap_or(0);
        let staleness_bonus = (days * 50).min(5_000);

        // Git weight: up to 3,000 points
        let (git_bonus, git_rationale) = if let Some(git) = &explanation.git_status {
            if git.is_dirty {
                (0, "active development with uncommitted changes")
            } else if git.is_merged {
                (3_000, "merged feature branch")
            } else {
                (1_500, "clean git branch")
            }
        } else {
            (1_000, "untracked directory")
        };

        // Size efficiency weight: up to 5,000 points
        let size_mb = entry.size_bytes / (1024 * 1024);
        let size_bonus = (size_mb * 5).min(5_000);

        let total_score = base_risk + staleness_bonus + git_bonus + size_bonus;

        let recovery_cmd = explanation
            .rebuild_plan
            .as_ref()
            .map(|r| r.description.clone());
        let git_branch = explanation
            .git_status
            .as_ref()
            .and_then(|g| g.branch.clone());
        let git_dirty = explanation
            .git_status
            .as_ref()
            .map(|g| g.is_dirty)
            .unwrap_or(false);

        let rationale = format!("{risk_rationale}, {git_rationale}, {days}d inactive");

        candidates.push(ReclaimCandidate {
            path: entry.path.clone(),
            artifact_label: explanation.artifact_label,
            kind_slug: explanation.artifact_kind.slug().to_string(),
            icon: explanation.artifact_kind.icon().to_string(),
            size_bytes: entry.size_bytes,
            formatted_size: explanation.formatted_size,
            risk_level: explanation.risk_level,
            days_inactive: explanation.source_staleness.map(|s| s.stale_days),
            git_branch,
            git_dirty,
            recovery_command: recovery_cmd,
            score: total_score,
            rationale,
        });
    }

    // Sort candidates descending by score
    candidates.sort_by_key(|a| std::cmp::Reverse(a.score));

    // Select candidates until target is satisfied
    let mut selected: Vec<ReclaimCandidate> = Vec::new();
    let mut proposed_bytes: u64 = 0;

    for cand in candidates {
        if proposed_bytes >= target_bytes {
            break;
        }
        proposed_bytes += cand.size_bytes;
        selected.push(cand);
    }

    let met_target = proposed_bytes >= target_bytes;

    ReclaimPlan {
        target_bytes,
        proposed_bytes,
        formatted_target: format_bytes(target_bytes),
        formatted_proposed: format_bytes(proposed_bytes),
        met_target,
        candidates: selected,
        pinned_skipped_count,
        pinned_skipped_bytes,
        total_scanned_bytes,
        profile_applied: profile.map(|p| p.slug().to_string()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::ArtifactKind;
    use std::time::SystemTime;

    #[test]
    fn test_parse_size_to_bytes() {
        assert_eq!(
            parse_size_to_bytes("10GB").unwrap(),
            10 * 1024 * 1024 * 1024
        );
        assert_eq!(parse_size_to_bytes("10G").unwrap(), 10 * 1024 * 1024 * 1024);
        assert_eq!(parse_size_to_bytes("500MB").unwrap(), 500 * 1024 * 1024);
        assert_eq!(parse_size_to_bytes("500m").unwrap(), 500 * 1024 * 1024);
        assert_eq!(
            parse_size_to_bytes("1.5GB").unwrap(),
            (1.5 * 1024.0 * 1024.0 * 1024.0) as u64
        );
        assert_eq!(
            parse_size_to_bytes("1TB").unwrap(),
            1024 * 1024 * 1024 * 1024
        );
        assert_eq!(parse_size_to_bytes("1024KB").unwrap(), 1024 * 1024);
        assert_eq!(parse_size_to_bytes("1048576B").unwrap(), 1048576);
        assert_eq!(parse_size_to_bytes("5").unwrap(), 5 * 1024 * 1024 * 1024); // default GB
        assert!(parse_size_to_bytes("").is_err());
        assert!(parse_size_to_bytes("0GB").is_err());
        assert!(parse_size_to_bytes("-5GB").is_err());
        assert!(parse_size_to_bytes("invalid").is_err());
    }

    #[test]
    fn test_format_bytes() {
        assert_eq!(format_bytes(500), "500 B");
        assert_eq!(format_bytes(1024), "1.00 KB");
        assert_eq!(format_bytes(10 * 1024 * 1024), "10.00 MB");
        assert_eq!(format_bytes(5 * 1024 * 1024 * 1024), "5.00 GB");
        assert_eq!(format_bytes(2 * 1024 * 1024 * 1024 * 1024), "2.00 TB");
    }

    #[test]
    fn test_plan_reclaim_budget_target() {
        let entries = vec![
            Entry {
                path: PathBuf::from("/tmp/proj1/target"),
                size_bytes: 4 * 1024 * 1024 * 1024, // 4 GB
                last_modified: Some(SystemTime::now()),
                kind: ArtifactKind::RustTarget,
                git_status: None,
                package_manager: None,
                workspace_root: None,
                custom_rule: None,
            },
            Entry {
                path: PathBuf::from("/tmp/proj2/target"),
                size_bytes: 6 * 1024 * 1024 * 1024, // 6 GB
                last_modified: Some(SystemTime::now()),
                kind: ArtifactKind::RustTarget,
                git_status: None,
                package_manager: None,
                workspace_root: None,
                custom_rule: None,
            },
            Entry {
                path: PathBuf::from("/tmp/proj3/node_modules"),
                size_bytes: 2 * 1024 * 1024 * 1024, // 2 GB
                last_modified: Some(SystemTime::now()),
                kind: ArtifactKind::NodeModules,
                git_status: None,
                package_manager: None,
                workspace_root: None,
                custom_rule: None,
            },
        ];

        // Ask for 5 GB
        let target = 5 * 1024 * 1024 * 1024;
        let plan = plan_reclaim(&entries, target, true, None);

        assert!(plan.met_target);
        assert!(plan.proposed_bytes >= target);
        assert!(!plan.candidates.is_empty());
    }
}
